"""Concatenate rendered scenes into the two deliverables, plus subtitles and the presenter script.

  out/prompt2own_demo.mp4         1920x1080, 30 fps, H.264 + AAC, voice normalized to -16 LUFS
  out/prompt2own_demo_silent.mp4  same picture, no audio track (for presenting live)
  out/prompt2own_demo.srt         subtitles (from manim-voiceover's per-scene .srt, offset)
  script.md                       narration with measured start times per line

Usage: python demo/assemble.py <quality_dir>   (e.g. 1080p30, or 480p15 for a preview)
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

DEMO = Path(__file__).resolve().parent
sys.path.insert(0, str(DEMO))
from narration import SCENES  # noqa: E402
from tts import provider, KOKORO_VOICE, KOKORO_SPEED  # noqa: E402

CLASS = {"s1_problem": "S1Problem", "s2_system": "S2System", "s3_run": "S3Run",
         "s4_findings": "S4Findings", "s5_next": "S5Next"}
OUT = DEMO / "out"


def sh(*a: str) -> str:
    return subprocess.run(a, check=True, capture_output=True, text=True).stdout


def dur(p: Path) -> float:
    return float(sh("ffprobe", "-v", "error", "-show_entries", "format=duration", "-of",
                    "default=nw=1:nk=1", str(p)))


def ts_srt(t: float) -> str:
    ms = int(round(t * 1000))
    return f"{ms // 3600000:02d}:{ms // 60000 % 60:02d}:{ms // 1000 % 60:02d},{ms % 1000:03d}"


def ts(t: float) -> str:
    return f"{int(t // 60)}:{t % 60:04.1f}"


def parse_srt(text: str):
    for block in re.split(r"\n\s*\n", text.strip()):
        lines = block.strip().splitlines()
        if len(lines) < 3:
            continue
        a, b = lines[1].split(" --> ")
        yield _sec(a), _sec(b), " ".join(lines[2:])


def _sec(s: str) -> float:
    h, m, rest = s.strip().split(":")
    sec, ms = rest.split(",")
    return int(h) * 3600 + int(m) * 60 + int(sec) + int(ms) / 1000


def main(q: str) -> None:
    OUT.mkdir(exist_ok=True)
    vids = []
    for sid, *_ in SCENES:
        v = DEMO / "media" / "videos" / sid / q / f"{CLASS[sid]}.mp4"
        if not v.exists():
            raise SystemExit(f"missing render {v}")
        vids.append((sid, v))

    lst = OUT / "concat.txt"
    lst.write_text("".join(f"file '{v}'\n" for _, v in vids))
    raw = OUT / "raw_concat.mp4"
    sh("ffmpeg", "-y", "-loglevel", "error", "-f", "concat", "-safe", "0", "-i", str(lst),
       "-c:v", "libx264", "-preset", "slow", "-crf", "18", "-pix_fmt", "yuv420p", "-r", "30",
       "-c:a", "aac", "-b:a", "192k", "-ar", "48000", str(raw))
    full = OUT / "prompt2own_demo.mp4"
    sh("ffmpeg", "-y", "-loglevel", "error", "-i", str(raw), "-c:v", "copy",
       "-af", "loudnorm=I=-16:TP=-1.5:LRA=11", "-c:a", "aac", "-b:a", "192k", "-ar", "48000",
       "-movflags", "+faststart", str(full))
    silent = OUT / "prompt2own_demo_silent.mp4"
    sh("ffmpeg", "-y", "-loglevel", "error", "-i", str(full), "-c:v", "copy", "-an",
       "-movflags", "+faststart", str(silent))
    raw.unlink()
    lst.unlink()

    # subtitles and presenter script with measured times
    srt, n, off = [], 1, 0.0
    lines = ["# Prompt2Own midway demo: presenter script", "",
             "Generated by `demo/assemble.py` after rendering; numbers come from `demo/data.py`.",
             f"Voice: {provider()}"
             + (f" ({KOKORO_VOICE}, speed {KOKORO_SPEED})" if provider() == "kokoro" else "")
             + ". Each line starts at the time shown, in both the voiced and the silent cut.", ""]
    late = []
    for (sid, v), (_, title, _, beats) in zip(vids, SCENES):
        d = dur(v)
        tj = json.loads((DEMO / "cache" / "timings" / f"{sid}.json").read_text())
        for b in tj["beats"]:
            # waits at the end of a beat are deliberate holds; real overrun = animation past audio
            over = b["anim_end"] - b["start"] - b["audio"]
            if over > 0.5:
                late.append(f"{sid} beat {b['beat']}: animations end {over:.2f} s after the sentence")
        lines += [f"## {ts(off)}–{ts(off + d)}  {title}  ({d:.1f} s)", ""]
        for b in tj["beats"]:
            lines.append(f"- **[{ts(off + b['start'])}]** {b['text']}")
        lines.append("")
        s = v.with_suffix(".srt")
        if s.exists():
            for a, b, txt in parse_srt(s.read_text()):
                srt.append(f"{n}\n{ts_srt(off + a)} --> {ts_srt(off + b)}\n{txt}\n")
                n += 1
        off += d
    total = dur(full)
    words = sum(len(b.split()) for *_, beats in SCENES for b in beats)
    lines += [f"**Total: {ts(total)} ({total:.1f} s), {words} words.**", ""]
    (OUT / "prompt2own_demo.srt").write_text("\n".join(srt))
    (DEMO / "script.md").write_text("\n".join(lines))

    loud = subprocess.run(["ffmpeg", "-hide_banner", "-i", str(full), "-af", "ebur128", "-f", "null",
                           "-"], capture_output=True, text=True).stderr
    m = re.findall(r"I:\s+(-?[\d.]+) LUFS", loud)
    print(f"full: {full}  {total:.2f} s  integrated loudness {m[-1] if m else '?'} LUFS")
    print(f"silent: {silent}  {dur(silent):.2f} s")
    print(f"srt: {n - 1} cues; script.md written")
    print("sync: " + ("OK, no beat's animations end > 0.5 s after its sentence" if not late
                      else "\n  " + "\n  ".join(late)))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "1080p30")
